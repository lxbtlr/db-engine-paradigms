// run_crcbench: CRC-32C lowerings, checked against the CPU's CRC32C
// instruction (x86 crc32, aarch64 crc32c) and timed. Also the source of the
// Godbolt harness for the same code.
//
// Per-key hash (runtime::CRC32Hash::hashKey, 8-byte keys, what VW_USE_CRC32
// runs): today's 2 CRCs per key; A: linearity, 1 CRC per key;
// B: Barrett reduction in carry-less-multiply lanes (x86 VPCLMULQDQ, 8 keys
// per zmm; aarch64 PMULL, 2 keys per register); C: slicing-by-8 tables
// (x86 vpgatherdd; aarch64 scalar, NEON has no gathers).
// Buffer CRC-32C: carry-less-multiply folding and scalar/vector hybrids
// generated by corsix/fast-crc32 (MIT or zlib, notice below), for x86
// (PCLMULQDQ/VPCLMULQDQ) and aarch64 (PMULL, EOR3).
//
// Every variant is compiled with its own target attribute and picked at run
// time by CPU features. CRC_MAX_ISA caps the tier, to exercise the paths of
// weaker CPUs: x86 sse|avx512 (no AVX-512 / no VPCLMULQDQ, e.g. Cascade
// Lake), aarch64 base|neon (no PMULL / no SHA3, e.g. Neoverse N1).
// Exit status 1 if any variant disagrees with the CRC32C instruction.
//
// Usage: run_crcbench     (optionally CRC_MAX_ISA=<tier> run_crcbench)
// --- harness (not part of the original code) ---
