static uint32_t crc32c_ref(uint32_t crc, const char* p, size_t n) { // standard CRC-32C
   crc = ~crc;
   for (size_t i = 0; i < n; ++i) crc = _mm_crc32_u8(crc, (uint8_t)p[i]);
   return ~crc;
}
template <typename F> static double bestNs(F&& f, int reps) {
   double best = 1e300;
   for (int r = 0; r < reps; ++r) {
      auto t0 = std::chrono::steady_clock::now();
      f();
      auto t1 = std::chrono::steady_clock::now();
      best = std::min(best, std::chrono::duration<double, std::nano>(t1 - t0).count());
   }
   return best;
}
int main() {
   initTables();
#if defined(__x86_64__)
   bool avx512 = __builtin_cpu_supports("avx512f") && __builtin_cpu_supports("avx512vl") &&
                 __builtin_cpu_supports("avx512dq");
   bool vpclmul = avx512 && __builtin_cpu_supports("vpclmulqdq");
   // CRC_MAX_ISA=sse|avx512 caps the variants used, to exercise the paths a
   // CPU without AVX-512 (sse) or without VPCLMULQDQ (avx512, e.g. Cascade
   // Lake) takes
   if (const char* cap = std::getenv("CRC_MAX_ISA")) {
      if (!std::strcmp(cap, "sse")) avx512 = vpclmul = false;
      else if (!std::strcmp(cap, "avx512")) vpclmul = false;
   }
   std::printf("cpu: avx512f/vl/dq=%d vpclmulqdq=%d\n", avx512, vpclmul);
#else
   const unsigned long hw = getauxval(AT_HWCAP);
   bool pmull = (hw & HWCAP_PMULL) != 0;
   bool sha3 = pmull && (hw & HWCAP_SHA3) != 0;
   // CRC_MAX_ISA=base|neon: no PMULL (base) or no SHA3/EOR3 (neon, e.g.
   // Neoverse N1)
   if (const char* cap = std::getenv("CRC_MAX_ISA")) {
      if (!std::strcmp(cap, "base")) pmull = sha3 = false;
      else if (!std::strcmp(cap, "neon")) sha3 = false;
   }
   std::printf("cpu: crc32=1 pmull=%d sha3=%d\n", pmull, sha3);
#endif
   int fails = 0;

   // per-key hash: 100000 keys, every variant against CRC32Hash::hashKey
   std::mt19937_64 rng(42);
   std::vector<uint64_t> keys(N);
   for (auto& k : keys) k = rng();
   keys[0] = 0, keys[1] = ~0ull, keys[2] = 0x04c11db7;
   std::vector<hash_t> ref(N), got(N);
   crc32_hash(keys.data(), ref.data());
   struct KeyImpl { const char* name; void (*fn)(const uint64_t*, hash_t*); bool ok; };
#if defined(__x86_64__)
   KeyImpl kimpl[] = {{"hash_scalar (2x crc32q)", crc32_hash, true},
                      {"A hash_linear (1x crc32q)", crc32_hash_linear, true},
                      {"B hash_vpclmul (Barrett, 8 keys/zmm)", crc32_hash_vpclmul, vpclmul},
                      {"C hash_gather (slicing-by-8, vpgatherdd)", crc32_hash_gather, avx512}};
#else
   KeyImpl kimpl[] = {{"hash_scalar (2x crc32cx)", crc32_hash, true},
                      {"A hash_linear (1x crc32cx)", crc32_hash_linear, true},
                      {"B hash_pmull (Barrett, 2 keys/reg)", crc32_hash_pmull, pmull},
                      {"C hash_tables (slicing-by-8, scalar)", crc32_hash_tables, true}};
#endif
   std::printf("\n%-42s %-9s %s\n", "per-key hash (100000 keys)", "check", "ns/key");
   for (auto& k : kimpl) {
      if (!k.ok) { std::printf("%-42s %-9s\n", k.name, "skipped"); continue; }
      k.fn(keys.data(), got.data());
      const bool same = got == ref;
      fails += !same;
      double ns = bestNs([&] { k.fn(keys.data(), got.data()); }, 20) / N;
      std::printf("%-42s %-9s %.3f\n", k.name, same ? "ok" : "MISMATCH", ns);
   }

   // buffer CRC-32C: sizes and misalignments against crc32c_ref
   std::vector<char> buf((1 << 20) + 64);
   for (auto& b : buf) b = (char)rng();
   struct BufImpl { const char* name; uint32_t (*fn)(uint32_t, const char*, size_t); bool ok; };
#if defined(__x86_64__)
   BufImpl bimpl[] = {{"sse_v4e (PCLMULQDQ fold)", sse_v4e::crc32_impl, true},
                      {"vpclmul_v4x2e (VPCLMULQDQ fold)", vpclmul_v4x2e::crc32_impl, vpclmul},
                      {"fusion_avx512_v9s3x4e (hybrid)", fusion_avx512_v9s3x4e::crc32_impl, avx512},
                      {"fusion_vpclmul_v4s5x3 (hybrid)", fusion_vpclmul_v4s5x3::crc32_impl, vpclmul}};
#else
   BufImpl bimpl[] = {{"neon_v12e_v1 (PMULL fold)", neon_v12e_v1::crc32_impl, pmull},
                      {"neon_v3s4x2e_v2 (hybrid)", neon_v3s4x2e_v2::crc32_impl, pmull},
                      {"neon_eor3_v9s3x2e_s3 (hybrid, EOR3)", neon_eor3_v9s3x2e_s3::crc32_impl, sha3}};
#endif
   const size_t sizes[] = {0, 1, 7, 8, 15, 63, 64, 65, 255, 256, 257, 1000, 4096, 12345, 65536, 1 << 20};
   std::printf("\n%-42s %-9s %10s %10s\n", "buffer CRC-32C", "check", "GB/s 4KiB", "GB/s 1MiB");
   {  // scalar crc32q chain for reference speed
      double ns4k = bestNs([&] { volatile uint32_t c = crc32c_ref(0, buf.data(), 4096); (void)c; }, 200);
      // (single call per sample is fine here: ~4 us)
      std::printf("%-42s %-9s %10.2f %10s\n", "bytewise crc32b (reference)", "-", 4096 / ns4k, "-");
   }
   for (auto& b : bimpl) {
      if (!b.ok) { std::printf("%-42s %-9s\n", b.name, "skipped"); continue; }
      bool same = true;
      for (size_t n : sizes)
         for (size_t off = 0; off < 8 && same; ++off)
            for (uint32_t seed : {0u, 0xffffffffu, 0x12345678u})
               same &= b.fn(seed, buf.data() + off, n) == crc32c_ref(seed, buf.data() + off, n);
      fails += !same;
      // 64 calls per sample: one 4 KiB call can take ~50 ns, near the clock's
      // resolution
      double ns4k = bestNs([&] {
         for (int r = 0; r < 64; ++r) { volatile uint32_t c = b.fn(r, buf.data(), 4096); (void)c; }
      }, 200) / 64;
      double ns1m = bestNs([&] { volatile uint32_t c = b.fn(0, buf.data(), 1 << 20); (void)c; }, 50);
      std::printf("%-42s %-9s %10.2f %10.2f\n", b.name, same ? "ok" : "MISMATCH", 4096 / ns4k,
                  double(1 << 20) / ns1m);
   }
   std::printf("\n%s\n", fails ? "FAILED" : "all variants match the CRC32C instruction");
   return fails != 0;
}
